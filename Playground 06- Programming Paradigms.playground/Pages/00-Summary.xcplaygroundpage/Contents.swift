 ## Why Paradigms Matter
 Different programming paradigms represent different ways of *thinking about problems*.

 - UIKit (and much of Apple’s frameworks) → **Object-Oriented**
 - Swift Standard Library → **Protocol-Oriented**
 - Swift functions & collections → **Functional**
 - SwiftUI → **Declarative**
 - Combine & async flows → **Reactive**

 Modern iOS apps often mix these paradigms together. Mastering them gives you flexibility to choose the right tool for the job.

