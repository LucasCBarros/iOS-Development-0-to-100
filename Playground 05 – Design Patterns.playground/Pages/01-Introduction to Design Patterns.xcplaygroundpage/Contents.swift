/*:
 ## 1. Introduction to Design Patterns

 Design Patterns are **general reusable solutions** to common problems in software design.\
 They are not code, but **templates** for how to solve recurring challenges.

 ---

 ### Categories
 - **Creational** → How objects are created (e.g., Singleton, Factory).
 - **Structural** → How objects are composed (e.g., Decorator).
 - **Behavioral** → How objects interact (e.g., Observer, Strategy).

 ---

 ### Real-world analogy
 - A recipe: not the dish itself, but the **instructions** to create it.
 - Multiple cooks can follow the same recipe and get the same result.

 ---

 ### In Swift
 Patterns often take advantage of:
 - Protocols.
 - Value vs. reference types.
 - Closures and generics.
 */
